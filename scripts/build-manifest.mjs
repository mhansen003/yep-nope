// Writes lib/images.js from whatever actually landed in public/e40, so a failed
// generation leaves a gap in the pool instead of a broken <img> on the site.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "public", "e40");
const files = readdirSync(dir).filter((f) => f.endsWith(".webp"));
const pick = (p) =>
  files.filter((f) => f.startsWith(`${p}-`)).sort().map((f) => `/e40/${f}`);

const yup = pick("yup");
const nope = pick("nope");

mkdirSync(join(process.cwd(), "lib"), { recursive: true });
writeFileSync(
  join(process.cwd(), "lib", "images.js"),
  `// GENERATED by scripts/build-manifest.mjs - do not edit by hand.
export const YUP_IMAGES = ${JSON.stringify(yup, null, 2)};

export const NOPE_IMAGES = ${JSON.stringify(nope, null, 2)};
`
);
console.log(`manifest: ${yup.length} yup, ${nope.length} nope`);
